export function getCattle(id: string): Cattle | undefined {
  return cattle.find((c) => c.id === id);
}

export function cattleLabel(id?: string): string {
  if (!id || id === "—") return "—";
  const c = getCattle(id);
  return c ? `${c.name} (${c.id})` : id;
}

