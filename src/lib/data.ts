// Female-line classes are eligible to be a dam; only an intact Bull can sire.
export function isFemaleClass(c: CattleClass): boolean {
  return c === "Cow" || c === "Heifer";
}
export function isMaleClass(c: CattleClass): boolean {
  return c === "Bull" || c === "Steer";
}
export function canBeDam(c: CattleClass): boolean {
  return c === "Cow" || c === "Heifer";
}
export function canBeSire(c: CattleClass): boolean {
  return c === "Bull";
}

// Badge colour by class: female-line purple, male-line blue, calves green.
export function classTone(c: CattleClass): "purple" | "blue" | "green" {
  if (c === "Cow" || c === "Heifer") return "purple";
  if (c === "Bull" || c === "Steer") return "blue";
  return "green";
}

